-- 1. 类目层级初始化（现有 10 个类目均为一级）
UPDATE `tb_shop_type`
SET `parent_id` = 0,
    `level`     = 1,
    `path`      = CAST(`id` AS CHAR)
WHERE `parent_id` = 0
  AND (`path` = '' OR `path` IS NULL);

-- 2. 从 tb_voucher 回填券类/秒杀类活动
INSERT INTO `tb_activity` (`shop_id`, `title`, `sub_title`, `description`, `images`,
                           `activity_type`, `category_id`, `tags`, `city`, `area`, `x`, `y`,
                           `original_price`, `pay_value`, `actual_value`, `stock`,
                           `begin_time`, `end_time`, `status`, `quality_score`,
                           `source_type`, `source_id`)
SELECT v.`shop_id`,
       v.`title`,
       v.`sub_title`,
       v.`rules`,
       COALESCE(SUBSTRING_INDEX(s.`images`, ',', 1), ''),
       CASE WHEN v.`type` = 1 THEN 4 ELSE 0 END,
       COALESCE(s.`type_id`, 1),
       '优惠券,代金券',
       '杭州',
       s.`area`,
       s.`x`,
       s.`y`,
       COALESCE(v.`actual_value`, 0),
       COALESCE(v.`pay_value`, 0),
       COALESCE(v.`actual_value`, 0),
       COALESCE(sv.`stock`, 0),
       CASE
           WHEN sv.`begin_time` IS NULL OR sv.`begin_time` < '2020-01-01 00:00:00'
               THEN '2026-10-01 00:00:00'
           ELSE sv.`begin_time` END,
       CASE
           WHEN sv.`end_time` IS NULL OR sv.`end_time` < '2020-01-01 00:00:00'
               THEN '2026-12-31 23:59:59'
           ELSE sv.`end_time` END,
       CASE WHEN v.`status` = 1 THEN 2 ELSE 3 END,
       50,
       1,
       v.`id`
FROM `tb_voucher` v
         LEFT JOIN `tb_shop` s ON s.`id` = v.`shop_id`
         LEFT JOIN `tb_seckill_voucher` sv ON sv.`voucher_id` = v.`id`
WHERE NOT EXISTS (SELECT 1
                  FROM `tb_activity` a
                  WHERE a.`source_type` = 1
                    AND a.`source_id` = v.`id`);

-- 3. 券挂接活动
UPDATE `tb_voucher` v
    JOIN `tb_activity` a ON a.`source_type` = 1 AND a.`source_id` = v.`id`
SET v.`activity_id` = a.`id`
WHERE v.`activity_id` IS NULL;

-- 4. 笔记挂接同商家的第一个在线活动，并让历史笔记可见
UPDATE `tb_blog` b
    JOIN (SELECT `shop_id`, MIN(`id`) AS `aid`
          FROM `tb_activity`
          WHERE `shop_id` IS NOT NULL
            AND `status` = 2
          GROUP BY `shop_id`) x ON x.`shop_id` = b.`shop_id`
SET b.`activity_id` = x.`aid`
WHERE b.`activity_id` IS NULL;

UPDATE `tb_blog`
SET `status`        = 1,
    `quality_score` = LEAST(100, COALESCE(`liked`, 0) * 5 + 50),
    `tags`          = COALESCE(`tags`, '探店,体验')
WHERE `status` = 0;

-- 5. 商家质量分与标签
UPDATE `tb_shop`
SET `quality_score` = LEAST(100, COALESCE(`score`, 0) * 2),
    `tags`          = COALESCE(`tags`, CONCAT('商家,', COALESCE(`area`, '杭州')))
WHERE `quality_score` = 0;

